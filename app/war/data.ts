import okrsJson from "@/data/okrs.json";
import ledgerJson from "@/data/ledger.json";
import deploysJson from "@/data/deploys.json";
import linksJson from "@/data/links.json";

/* Real data only — everything on /war derives from versioned JSON in /data
 * (see CLAUDE.md). No mock telemetry. */

/* ---------------------------------------------------------------------------
 * ONE-EDIT SWITCH — repo visibility.
 *
 * Karl's ruling (2026-07-28): the repo goes PUBLIC at launch, gated on a clean
 * all-refs secrets sweep by Jul 30. While the repo is private, every GitHub URL
 * on this page — the links-rail row AND every per-commit link in the Growth
 * Ledger — is a public 404.
 *
 * If the sweep is not clean, flip this to `false`. That single edit removes the
 * GitHub row from the rail and drops every commit href. Nothing else to change.
 * ------------------------------------------------------------------------- */
export const REPO_PUBLIC = true;

export type StatusRole = "good" | "warning" | "serious" | "critical";

export type KeyResult = { id: string; title: string; progress: number; note?: string };
export type Objective = { id: string; title: string; due: string; keyResults: KeyResult[] };
export type Commit = { sha: string; t: number; msg: string };
export type Deploy = { id?: string; t: number; url: string; target: string; sha: string };
export type LinkItem = {
  name: string;
  url: string;
  note?: string;
  /** Row is a github.com URL: hidden while REPO_PUBLIC is false. */
  requiresPublicRepo?: boolean;
};

export type LedgerEntry = {
  id: string;
  t: number;
  kind: "commit" | "deploy";
  title: string;
  detail?: string;
  href?: string;
};

/* data/ledger.json is regenerated by scripts/gen-ledger.mjs at prebuild; the
 * committed copy is the fallback when git history is unavailable or truncated.
 * `builtAt` and friends only exist on regenerated files, hence optional. */
type LedgerFile = {
  /** Timestamp of the newest commit in `commits`. */
  generatedAt: number;
  /** Wall clock at the build that produced this file. Not request time. */
  builtAt?: number;
  /** "git" when derived at build, "committed" when the fallback was kept. */
  source?: string;
  /** True when derived from a shallow checkout (history may be truncated). */
  shallow?: boolean;
  commits: Commit[];
};

const ledger = ledgerJson as LedgerFile;

const STEP_MS = 5 * 60 * 1000;

/* Request-scoped anchor on a 5-min grid: stable within a window, identical
 * between server render and hydration. Use it for "now"-relative chrome
 * (countdown, "x ago") only — never to window a build-time data set. */
export function currentAnchor(): number {
  return Math.floor(Date.now() / STEP_MS) * STEP_MS;
}

/** When the JSON rendered on this page was built. Not when it was requested. */
export function getBuildTime(): number {
  return ledger.builtAt ?? ledger.generatedAt;
}

export function getObjectives(): Objective[] {
  return okrsJson.objectives;
}

/* Rows with an empty URL never ship — a link rail that renders "add URL here"
 * to the public is a dead link (DoD #4). */
export function getLinks(): LinkItem[] {
  return (linksJson as LinkItem[]).filter(
    (l) => l.url.length > 0 && (REPO_PUBLIC || !l.requiresPublicRepo),
  );
}

export function getCommits(): Commit[] {
  return ledger.commits;
}

/** Newest commit timestamp in the ledger — the anchor for commit windows. */
export function lastCommitAt(): number {
  return getCommits().reduce((max, c) => (c.t > max ? c.t : max), 0);
}

/** Recorded deploys, newest first. See scripts/sync-deploys.mjs for provenance. */
export function getDeploys(): Deploy[] {
  return (deploysJson as Deploy[]).slice().sort((a, b) => b.t - a.t);
}

export function getProductionDeploys(): Deploy[] {
  return getDeploys().filter((d) => d.target === "production");
}

const repoUrl = REPO_PUBLIC
  ? ((linksJson as LinkItem[]).find((l) => l.name === "GitHub")?.url ?? "")
  : "";

function bareHost(url: string): string {
  return url.replace(/^https?:\/\//, "");
}

export function getLedger(): LedgerEntry[] {
  const commits: LedgerEntry[] = getCommits().map((c) => ({
    id: `c-${c.sha}`,
    t: c.t,
    kind: "commit",
    title: c.msg,
    detail: c.sha.slice(0, 7),
    href: repoUrl ? `${repoUrl}/commit/${c.sha}` : undefined,
  }));
  /* Only the newest deploy is still serving; superseded deployment URLs are
   * not linked (they are auth-walled or gone — see DoD #4). */
  const all = getDeploys();
  const live = all[0];
  const deploys: LedgerEntry[] = all.map((d) => ({
    id: `d-${d.id ?? d.sha}-${d.t}`,
    t: d.t,
    kind: "deploy",
    title: `Deployed to ${d.target}`,
    detail:
      d === live ? `${d.sha.slice(0, 7)} · live at ${bareHost(d.url)}` : `${d.sha.slice(0, 7)} · superseded`,
    href: d === live ? d.url : undefined,
  }));
  return [...commits, ...deploys].sort((a, b) => b.t - a.t);
}

/* Commits per UTC day for the `days`-day window ending on the NEWEST COMMIT,
 * oldest → newest.
 *
 * Deliberately not wall-clock anchored: the ledger is a build-time snapshot, so
 * a trailing window over "now" drains to zero days after the last build and
 * renders a flat line under a live clock. The tile label states the anchor. */
export function commitsPerDay(days = 7): number[] {
  const day = (x: number) => Math.floor(x / 86400000);
  const end = day(lastCommitAt());
  const counts = new Array<number>(days).fill(0);
  for (const c of getCommits()) {
    const idx = days - 1 - (end - day(c.t));
    if (idx >= 0 && idx < days) counts[idx] += 1;
  }
  return counts;
}

export function daysUntil(dateISO: string, anchor: number): number {
  const [y, m, d] = dateISO.split("-").map(Number);
  const end = Date.UTC(y, m - 1, d, 23, 59, 59);
  return Math.max(0, Math.ceil((end - anchor) / 86400000));
}

export function objectiveProgress(o: Objective): number {
  if (o.keyResults.length === 0) return 0;
  return o.keyResults.reduce((s, kr) => s + kr.progress, 0) / o.keyResults.length;
}
